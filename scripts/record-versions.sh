#!/usr/bin/env bash
# record-versions.sh: write VERSIONS.md and versions.lock from what is installed now.
#
#   scripts/record-versions.sh          regenerate both files
#   scripts/record-versions.sh --get K  print the current version of package K
#
# Source commits come from pins.env and Python packages from requirements.txt;
# those are pinned. System packages can't be pinned on a rolling distro, so
# their versions are recorded here and doctor.sh warns when they drift.
set -euo pipefail
cd "$(dirname "$(dirname "$(readlink -f "$0")")")"
. ./pins.env
. /etc/os-release

if [[ " ${ID:-} ${ID_LIKE:-} " == *" arch "* ]]; then
    pkgs=(mips-linux-gnu-binutils clang lld llvm cmake ninja python git sdl2-compat gtk3
          vulkan-icd-loader vulkan-tools nvidia-utils)
    pkgver() { pacman -Q "$1" 2>/dev/null | cut -d' ' -f2; }
else
    pkgs=(binutils-mips-linux-gnu clang lld llvm cmake ninja-build python3 git libsdl2-dev
          libgtk-3-dev vulkan-tools)
    pkgver() { dpkg-query -W -f='${Version}' "$1" 2>/dev/null; }
fi

if [[ ${1:-} == --get ]]; then
    pkgver "$2"
    exit
fi

{
    echo "# versions.lock: system package versions when VERSIONS.md was recorded (doctor.sh compares)."
    for p in "${pkgs[@]}"; do
        v=$(pkgver "$p")
        [[ -n $v ]] && echo "$p=$v"
    done
} >versions.lock

{
    cat <<MD
# Versions

Generated by \`scripts/record-versions.sh\` on $(date +%F) ($PRETTY_NAME, $(uname -m)). Don't edit by hand.

## Source tools (pinned in \`pins.env\`)

| Repo | Commit | Commit date | Used for |
|---|---|---|---|
MD
    row() {  # row <name> <url> <commit> <date> <use>
        echo "| [$1](${2%.git}) | \`${3:0:12}\` | $4 | $5 |"
    }
    row N64Recomp "$N64RECOMP_URL" "$N64RECOMP_COMMIT" "$N64RECOMP_DATE" "built into \`bin/\` by build.sh"
    row N64ModernRuntime "$N64MODERNRUNTIME_URL" "$N64MODERNRUNTIME_COMMIT" "$N64MODERNRUNTIME_DATE" "default submodule for new games"
    row RT64 "$RT64_URL" "$RT64_COMMIT" "$RT64_DATE" "default submodule for new games"
    row Zelda64Recomp "$ZELDA64RECOMP_URL" "$ZELDA64RECOMP_REF_COMMIT" "$ZELDA64RECOMP_REF_DATE" "reference shell (\`recomp-frontend\` branch), read only"
    cat <<MD

Why these: see the comments in \`pins.env\`. N64Recomp's own submodules (rabbitizer, ELFIO, fmt,
toml++, sljit) are fixed by its commit.

## Python (\`.venv\`, pinned in \`requirements.txt\`)

Python $(.venv/bin/python -c 'import platform; print(platform.python_version())'), pip $(.venv/bin/pip --version | cut -d' ' -f2).

| Package | Version |
|---|---|
MD
    sed -n 's/^\(.*\)==\(.*\)$/| \1 | \2 |/p' requirements.txt
    cat <<MD

## System packages (recorded, not pinned)

Installed by \`install.sh\`. A rolling distro moves these; \`doctor.sh\` warns when one differs from
this list. Rerun \`scripts/record-versions.sh\` after checking a new version still works.

| Package | Version |
|---|---|
MD
    for p in "${pkgs[@]}"; do
        v=$(pkgver "$p")
        echo "| $p | ${v:-not installed} |"
    done
} >VERSIONS.md
echo "record-versions.sh: wrote VERSIONS.md and versions.lock"
